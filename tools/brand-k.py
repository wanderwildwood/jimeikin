#!/usr/bin/env python3
"""Regenerates app/src/store/res/values*/brand.xml: every main string that says "Music Box"
again, as "Music Box K", so the K app (the store flavour) names itself in every language
without the full app's strings being touched. Run after adding or changing a string in
app/src/main/res that contains "Music Box"; BrandTest fails when one is missing.
Strings the store flavour defines itself (app/src/store/res/values/strings.xml) are edited there."""
import re, pathlib
root = pathlib.Path(__file__).resolve().parent.parent / "app/src"
own = set(re.findall(r'name="([^"]+)"', (root / "store/res/values/strings.xml").read_text()))
for d in ("values", "values-de", "values-fr"):
    src = (root / "main/res" / d / "strings.xml").read_text()
    out = []
    for m in re.finditer(r'    <string name="([^"]+)"([^>]*)>(.*?)</string>', src, re.S):
        name, attrs, text = m.groups()
        if "Music Box" in text and name not in own and 'translatable="false"' not in attrs:
            out.append(f'    <string name="{name}"{attrs}>{text.replace("Music Box", "Music Box K")}</string>')
    dest = root / "store/res" / d
    dest.mkdir(parents=True, exist_ok=True)
    (dest / "brand.xml").write_text(
        '<?xml version="1.0" encoding="utf-8"?>\n<!-- Generated by tools/brand-k.py: Music Box K\'s name in place of Music Box. Do not edit by hand. -->\n<resources>\n'
        + "\n".join(out) + "\n</resources>\n")
    print(d, len(out))
